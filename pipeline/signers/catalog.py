"""Curated Declaration-signer catalog.

Primary dates: NARA Signers Factsheet. Wikipedia infobox + Bioguide are
corroboration. Wikidata P569 precision=11 is QA only — never a date source.

Do not invent day-of-year values. Year-only NARA rows stay year-only even
when Wikidata or Wikipedia later claims a day.
"""

from __future__ import annotations

from typing import Literal

NARA_FACTSHEET_URL = "https://www.archives.gov/founding-docs/signers-factsheet"
NARA_FACTSHEET_PDF = (
    "https://www.archives.gov/files/founding-docs/declaration-signers-gallery-facts.pdf"
)
BIOGUIDE_URL = "https://bioguide.congress.gov/search/bio/{id}"

SignerStatus = Literal["verified", "year_only", "contested"]
CalendarNote = Literal["new_style", "nara_day"]

COLONY_NAMES: dict[str, str] = {
    "CT": "Connecticut",
    "DE": "Delaware",
    "GA": "Georgia",
    "MD": "Maryland",
    "MA": "Massachusetts",
    "NH": "New Hampshire",
    "NJ": "New Jersey",
    "NY": "New York",
    "NC": "North Carolina",
    "PA": "Pennsylvania",
    "RI": "Rhode Island",
    "SC": "South Carolina",
    "VA": "Virginia",
}

YEAR_ONLY_NOTE = (
    "NARA records only a year (circa). The day of birth is unknown. "
    "No birth card is computed and no signer page is published."
)

HANCOCK_HOLD = (
    "Held: NARA lists 1/12/1737 (Old Style); Wikipedia lists January 23, 1737 "
    "(New Style). The OS/NS pair is contested for this set."
)
HARRISON_HOLD = (
    "Held: NARA lists 4/7/1726; Wikipedia lists April 5, 1726. "
    "The day is contested."
)
HEWES_HOLD = (
    "Held: NARA and the Wikipedia infobox list July 9, 1730, but a January 23, "
    "1730 variant remains in circulation. The day is contested."
)


def _entry(
    *,
    name: str,
    slug: str,
    colony_code: str,
    wikipedia_title: str,
    qid: str,
    bioguide_id: str,
    nara_birth_raw: str,
    nara_death: str | None,
    status: SignerStatus,
    public_birth_date: str | None,
    wikipedia_birth: str | None,
    calendar_note: CalendarNote | None,
    footnote: str | None,
    hold_reason: str | None = None,
) -> dict:
    return {
        "name": name,
        "slug": slug,
        "colony_code": colony_code,
        "colony": COLONY_NAMES[colony_code],
        "wikipedia_title": wikipedia_title,
        "qid": qid,
        "bioguide_id": bioguide_id,
        "nara_birth_raw": nara_birth_raw,
        "nara_death": nara_death,
        "status": status,
        "public_birth_date": public_birth_date,
        "wikipedia_birth": wikipedia_birth,
        "calendar_note": calendar_note,
        "footnote": footnote,
        "hold_reason": hold_reason,
    }


