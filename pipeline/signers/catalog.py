def signers_by_status(status: SignerStatus) -> list[dict]:
    return [row for row in SIGNERS if row["status"] == status]


def verified_signers() -> list[dict]:
    return signers_by_status("verified")


def year_only_signers() -> list[dict]:
    return signers_by_status("year_only")


def contested_signers() -> list[dict]:
    return signers_by_status("contested")


