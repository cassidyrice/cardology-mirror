// Browser plugin not available in this session; use installed Playwright + Chrome.
import {chromium} from 'playwright';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const output=resolve(process.argv[2]||'reports/qa');
await mkdir(output,{recursive:true,mode:0o700});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true});
try{
  const context=await browser.newContext({viewport:{width:1440,height:1000},timezoneId:'America/Denver',acceptDownloads:true});
  const errors=[],network=[];
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  page.on('request',request=>{if(/^https?:/.test(request.url()))network.push(request.url());});
  await page.goto(pathToFileURL(resolve('ui/report.html')).href);
  assert.equal(await page.title(),'Report builder · My Card Blueprint');
  const preview=page.frameLocator('#report-frame');
  await preview.locator('h1').waitFor();
  assert.ok((await preview.locator('.prepared').textContent()).includes('Sample Client'));
  const basePages=await preview.locator('.page').count();
  assert.ok(basePages>10);
  await page.screenshot({path:resolve(output,'report-builder.png'),fullPage:true});
  await page.locator('#writing-tab').click();
  await page.locator('#section-copy').fill('Personal writing sample.');
  await page.locator('#reviewed').check();
  await page.locator('#update-preview').click();
  await preview.locator('.personal-copy').filter({hasText:'Personal writing sample.'}).waitFor();
  assert.ok((await preview.locator('footer').first().textContent()).includes('Reader reviewed'));
  await page.locator('#details-tab').click();await page.locator('#offer').selectOption('chemistry');
  await page.locator('#update-preview').click();await preview.locator('h1').filter({hasText:'The Chemistry Check'}).waitFor();
  await page.locator('#writing-tab').click();await page.locator('#section-copy').fill('Chemistry sample.');
  await page.locator('#details-tab').click();await page.locator('#offer').selectOption('timing-map');
  await page.locator('#writing-tab').click();assert.equal(await page.locator('#section-copy').inputValue(),'Personal writing sample.');
  await page.locator('#section-copy').fill('');await page.locator('#details-tab').click();
  await page.locator('#client-name').fill('QA Reader');
  assert.ok(await page.locator('#export-html').isDisabled());
  await page.locator('#writing-tab').click();
  await page.locator('#reader-notes').fill('A personal observation.\n<script>This is plain text.</script>');
  await page.locator('#details-tab').click();
  await page.locator('#report-date').fill('2026-10-15');
  await page.getByRole('button',{name:'Update preview'}).click();
  await preview.locator('.prepared').filter({hasText:'QA Reader'}).waitFor();
  assert.equal(await preview.locator('.page').count(),basePages+1);
  await page.locator('#report-page').selectOption(String(basePages-1));
  assert.ok((await preview.locator('.personal-copy').textContent()).includes('<script>'));
  let pending=page.waitForEvent('download');await page.locator('#save-draft').click();
  const draftDownload=await pending;const draftPath=resolve(output,'sample.draft.json');await draftDownload.saveAs(draftPath);
  const draft=JSON.parse(await readFile(draftPath,'utf8'));assert.equal(draft.people[0].name,'QA Reader');
  await page.locator('#details-tab').click();
  await page.locator('#client-name').fill('Other name');
  page.once('dialog',dialog=>dialog.accept());await page.locator('#load-sample').click();
  await page.locator('#draft-file').setInputFiles(draftPath);
  await preview.locator('.prepared').filter({hasText:'QA Reader'}).waitFor();
  assert.equal(await page.locator('#reader-notes').inputValue(),draft.notes);
  pending=page.waitForEvent('download');await page.locator('#export-html').click();
  const htmlDownload=await pending;const htmlPath=resolve(output,'sample-reading.html');await htmlDownload.saveAs(htmlPath);
  pending=page.waitForEvent('download');await page.locator('#export-engine').click();
  const engineDownload=await pending;await engineDownload.saveAs(resolve(output,'sample-reading.engine.json'));
  const engine=JSON.parse(await readFile(resolve(output,'sample-reading.engine.json'),'utf8'));assert.equal(engine.window.end,'2027-10-14');assert.equal(engine.people.length,3);
  const html=await readFile(htmlPath,'utf8');assert.ok(!html.includes('<script>'));assert.ok(html.includes('&lt;script&gt;'));
  await page.locator('#details-tab').click();
  await page.locator('#report-birthdate').fill('2000-12-31');await page.locator('#update-preview').click();
  assert.ok((await page.locator('#report-error').textContent()).includes('Joker'));
  assert.ok(await page.locator('#save-pdf').isDisabled());
  await page.locator('#report-birthdate').fill(draft.people[0].birthdate);await page.locator('#update-preview').click();
  await preview.locator('h1').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:resolve(output,'report-mobile.png'),fullPage:true});
  const printPage=await context.newPage();await printPage.setContent(html);await printPage.evaluate(()=>document.fonts.ready);await printPage.emulateMedia({media:'print'});
  const layout=await printPage.locator('.page').evaluateAll(pages=>pages.map(section=>{
    const footer=section.querySelector('footer').getBoundingClientRect();
    const items=[...section.children].filter(child=>child.tagName!=='FOOTER');
    return {title:section.querySelector('h2').textContent,height:section.getBoundingClientRect().height,overlap:items.some(child=>child.getBoundingClientRect().bottom>footer.top+1)};
  }));
  assert.deepEqual(layout.filter(page=>page.overlap),[],'Report content overlaps a footer');
  await printPage.pdf({path:resolve(output,'sample-reading.pdf'),format:'A4',printBackground:true,preferCSSPageSize:true});
  await printPage.emulateMedia({media:'screen'});await printPage.setViewportSize({width:900,height:1100});
  await printPage.screenshot({path:resolve(output,'sample-cover.png')});
  assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
  const result={basePages,pagesWithNotes:basePages+1,checks:['preview','offer switching','writing preservation','review status','engine JSON export','dirty export block','notes escaping','page selection','draft round trip','HTML download','Joker refusal','mobile overflow','print footer layout','PDF export','no network requests','no console errors'],layout};
  await writeFile(resolve(output,'qa.json'),JSON.stringify(result,null,2),{mode:0o600});
  console.log(JSON.stringify({output,...result,layout:undefined},null,2));
}finally{await browser.close();}
